def carbon_ledger(system):
    columns = (
        ("known_air_c", "Air now*" if system == "CCUS" else "Air now"),
        ("stored_c", "Stored"),
        ("jet_c", "In jet fuel"),
        ("diesel_c", "In diesel"),
        ("naphtha_c", "In naphtha"),
    )
    if system == "CCS":
        columns = columns[:2]
    rows = []
    for origin, label in (
        ("fossil_fuel", "Fossil fuel carbon"),
        ("non_fossil_fuel", "Non-fossil fuel carbon"),
    ):
        values = DETAIL["systems"][system][origin]
        rows.append(
            html.Tr(
                [
                    html.Th(label, scope="row"),
                    html.Td(f'{values["inlet_c"]:.1f}', className="carbon-inlet"),
                    *[
                        html.Td(f"{values[key]:.1f}", className="carbon-" + key)
                        for key, _ in columns
                    ],
                ]
            )
        )
    return html.Div(
        [
            html.Div(
                [
                    html.Strong("Fuel-carbon balance only"),
                    html.Span("kg C per tonne clinker · carbon mass, not a GWP score"),
                ],
                className="carbon-ledger-heading",
            ),
            html.Table(
                [
                    html.Thead(
                        html.Tr(
                            [
                                html.Th("Origin"),
                                html.Th("Input ="),
                                *[html.Th(label) for _, label in columns],
                            ]
                        )
                    ),
                    html.Tbody(rows),
                ]
            ),
        ],
        className="carbon-ledger",
    )


def capture_detail(system):
    if system == "CCUS":
        non = DETAIL["systems"][system]["non_fossil_fuel"]
        note = html.Div(
            [
                html.Strong(f'{non["jet_kg"]:.1f} kg jet fuel'),
                html.Span("→ used one year later →"),
                html.Strong(f'{non["jet_combustion_co2_kg"]:.0f} kg non-fossil CO₂'),
                html.Span(
                    f'*Includes {non["assumed_residual_co2_kg"]:.0f} kg CO₂ from burning the remaining carbon this year, as assumed here. No heat credit.'
                ),
            ],
            className="capture-fuel-use",
        )
    else:
        note = html.P(
            "90% capture → 5% liquefaction loss → 1.44% loss of loaded CO₂ in transport. Rates follow the published SI.2 inventory.",
            className="capture-balance-note",
        )
    return html.Div(
        [
            html.Figure(
                html.Img(
                    src="data:image/svg+xml;charset=utf-8,"
                    + quote(capture_svg(system)),
                    alt=f"{system} carbon routing with a fuel-carbon ledger. Calcination and steam-supply carbon are not quantified.",
                    className="system-svg",
                ),
                className="capture-detail-figure",
            ),
            carbon_ledger(system),
            *([uop_route()] if system == "CCUS" else []),
            note,
            html.P(
                "Calcination and capture-boiler carbon are not quantified here."
                + (
                    " All three fuels burn one year later."
                    if system == "CCUS"
                    else ""
                ),
                className="capture-basis-note",
            ),
        ],
        className="capture-detail-layout" + (" capture-detail-uop" if system == "CCUS" else ""),
    )


