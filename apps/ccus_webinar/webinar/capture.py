def _process(x, y, w, kind, title, note, tone="carbon", compact=False):
    h = 70 if compact else 110
    b = _box(x, y, w, h)
    if compact:
        b += _icon(kind, x + 8, y + 8, 45, tone)
        b += _text(x + 62, y + 28, title, "label") + _text(x + 62, y + 49, note, "note")
    else:
        b += _icon(kind, x + w / 2 - 28, y + 6, 56, tone)
        b += _text(x + w / 2, y + 81, title, "node-title", "middle")
        b += _text(x + w / 2, y + 101, note, "note", "middle")
    return b


def _origin_arrow(path, index):
    key, color, _ = ORIGINS[index]
    return f'<path data-origin="{key}" d="{path}" fill="none" stroke="{color}" stroke-width="2.8" stroke-linejoin="round" marker-end="url(#origin-{key})"/>'


