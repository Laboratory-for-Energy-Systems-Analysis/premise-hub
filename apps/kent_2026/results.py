def map_configuration(state: str = "baseline") -> dict:
    """Human-readable fingerprint for one precomputed decision surface."""
    return MAP_CONFIGURATIONS.get(state, MAP_CONFIGURATIONS["baseline"])


def _valid_map_values(state: str) -> list[list[float | None]]:
    return decision_map(state)["values"]["climate change"]


def _mean(values) -> float:
    clean = [float(value) for value in values if value is not None]
    return sum(clean) / len(clean) if clean else 0.0


@lru_cache(maxsize=1)
def sensitivity_ranking() -> list[dict]:
    """Rank visible result-surface spreads; this is not a global sensitivity analysis."""
    baseline = _valid_map_values("baseline")
    row_means = [_mean(row) for row in baseline]
    column_means = [
        _mean(row[column] for row in baseline)
        for column in range(len(baseline[0]))
    ]
    baseline_mean = _mean(value for row in baseline for value in row)

    def variant_spread(*states: str) -> float:
        means = [baseline_mean]
        for state in states:
            values = _valid_map_values(state)
            means.append(_mean(value for row in values for value in row))
        return max(means) - min(means)

    factors = [
        ("Annual distance", max(row_means) - min(row_means), "5–20k km/y"),
        ("Decision year", max(column_means) - min(column_means), "2020–2035"),
        ("Successor size", variant_spread("small_bev", "large_bev"), "small–large/SUV"),
        ("Vehicle lifetime", variant_spread("short_life", "long_life"), "150–250k km"),
        ("Energy-system future", variant_spread("transition", "rapid"), "three futures"),
    ]
    return [
        {"factor": factor, "spread_tonnes": spread / 1000, "range": range_label}
        for factor, spread, range_label in sorted(factors, key=lambda item: item[1], reverse=True)
    ]


