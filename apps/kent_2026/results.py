def landscape_state(lifetime_km: int = 200_000, horizon: int = 2040) -> dict:
    lookup = slide10_landscape()
    key = f"{int(lifetime_km)}|{int(horizon)}"
    try:
        return lookup["states"][key]
    except KeyError as exc:
        raise KeyError(f"Missing precomputed landscape state: {key}") from exc


def cumulative_sensitivity(
    lifetime_km: int = 200_000,
    annual_km: int = 12_000,
    electricity: str = "reference",
    fuel: str = "petrol",
    indicator: str = "climate change",
) -> dict:
    lookup = slide9_sensitivity()
    key = f"{int(lifetime_km)}|{int(annual_km)}|{electricity}|{fuel}"
    try:
        configuration = dict(lookup["configurations"][key])
    except KeyError as exc:
        raise KeyError(f"Missing precomputed slide-9 configuration: {key}") from exc
    if indicator == "particulate matter formation":
        configuration.update({
            "keep_t": configuration["keep_pm_milli"],
            "replace_t": configuration["replace_pm_milli"],
            "break_even_year": configuration["pm_break_even_year"],
            "delta_2060_t": configuration["pm_delta_2060_milli"],
            "display_unit": "10⁻³ disease incidences",
        })
    elif indicator != "climate change":
        raise ValueError(f"Unsupported slide-9 indicator: {indicator}")
    else:
        configuration["display_unit"] = "t CO₂-eq"
    configuration["indicator"] = indicator
    return configuration


def profile_key(
    cohort: int,
    powertrain: str,
    size: str = "Medium",
    annual_km: int = 12_000,
    lifetime_km: int = 200_000,
    case: str = "baseline",
) -> str:
    return f"{case}|{cohort}|{size}|{powertrain}|{annual_km}|{lifetime_km}"


def profile(**kwargs) -> dict:
    key = profile_key(**kwargs)
    try:
        return bundle()["profiles"][key]
    except KeyError as exc:
        raise KeyError(f"Missing precomputed vehicle profile: {key}") from exc


def last_use_year(cohort: int, annual_km: int, lifetime_km: int) -> int:
    return cohort + math.ceil(lifetime_km / annual_km) - 1


def _add_profile(target: dict, source: dict, start: int, stop: int) -> None:
    for category, years in source["annual"].items():
        category_target = target.setdefault(category, {})
        for year, stages in years.items():
            numeric_year = int(year)
            if start <= numeric_year <= stop:
                stage_target = category_target.setdefault(year, {})
                for stage, value in stages.items():
                    stage_target[stage] = stage_target.get(stage, 0.0) + float(value)


def _combine_annual(target: dict, source: dict) -> None:
    for category, years in source.items():
        category_target = target.setdefault(category, {})
        for year, stages in years.items():
            stage_target = category_target.setdefault(year, {})
            for stage, value in stages.items():
                stage_target[stage] = stage_target.get(stage, 0.0) + float(value)


def _nominal_distance(cohort: int, year: int, annual_km: int, lifetime_km: int) -> float:
    age = year - cohort
    if age < 0:
        return 0.0
    travelled = age * annual_km
    return float(max(0, min(annual_km, lifetime_km - travelled)))


def _stage_rate(source: dict, category: str, stage: str, year: int) -> float:
    cohort = source["cohort"]
    annual_km = source["annual_km"]
    lifetime_km = source["lifetime_km"]
    years = source["annual"].get(category, {})
    value = years.get(str(year), {}).get(stage)
    nominal = _nominal_distance(cohort, year, annual_km, lifetime_km)
    if value is not None and nominal > 0:
        return float(value) / nominal
    nominal_last = cohort + math.ceil(lifetime_km / annual_km) - 1
    if year <= nominal_last:
        return 0.0
    candidates = []
    for event_year, stages in years.items():
        distance = _nominal_distance(cohort, int(event_year), annual_km, lifetime_km)
        if stage in stages and distance > 0:
            candidates.append((int(event_year), float(stages[stage]) / distance))
    return max(candidates)[1] if candidates else 0.0


def _allocate_vehicle(
    cohort: int,
    first_year_km: float,
    annual_km: int,
    lifetime_km: int,
    stop: int,
) -> tuple[dict[int, float], bool, int, float]:
    allocations: dict[int, float] = {}
    remaining = float(lifetime_km)
    year = cohort
    capacity = float(first_year_km)
    while year <= stop and remaining > 1e-9:
        distance = min(capacity, remaining)
        allocations[year] = distance
        remaining -= distance
        if remaining <= 1e-9:
            return allocations, True, year, capacity - distance
        year += 1
        capacity = float(annual_km)
    return allocations, False, min(year - 1, stop), 0.0


def _add_scheduled_vehicle(
    target: dict,
    source: dict,
    allocations: dict[int, float],
    *,
    complete: bool,
    final_use_year: int,
    stop: int,
) -> None:
    for category, years in source["annual"].items():
        category_target = target.setdefault(category, {})
        for event_year, stages in years.items():
            numeric_year = int(event_year)
            if numeric_year > stop:
                continue
            for stage, value in stages.items():
                if stage != "manufacturing":
                    continue
                row = category_target.setdefault(event_year, {})
                row[stage] = row.get(stage, 0.0) + float(value)

        for year, distance in allocations.items():
            row = category_target.setdefault(str(year), {})
            for stage in ("use", "maintenance"):
                value = _stage_rate(source, category, stage, year) * distance
                if abs(value) > 1e-15:
                    row[stage] = row.get(stage, 0.0) + value
            if not row:
                category_target.pop(str(year), None)

        cumulative = 0.0
        crossings = []
        for year, distance in allocations.items():
            cumulative += distance
            crossings.append((cumulative, year))
        for event_year, stages in years.items():
            if "replacement" not in stages:
                continue
            threshold = min(
                source["lifetime_km"],
                (int(event_year) - source["cohort"] + 1) * source["annual_km"],
            )
            target_year = next((year for distance, year in crossings if distance + 1e-9 >= threshold), None)
            if target_year is not None and target_year <= stop:
                row = category_target.setdefault(str(target_year), {})
                row["replacement"] = row.get("replacement", 0.0) + float(stages["replacement"])

        if complete and final_use_year + 1 <= stop:
            eol = sum(float(stages.get("end of life", 0.0)) for stages in years.values())
            if abs(eol) > 1e-15:
                row = category_target.setdefault(str(final_use_year + 1), {})
                row["end of life"] = row.get("end of life", 0.0) + eol


def sequence(
    *,
    first_cohort: int,
    powertrain: str,
    size: str,
    annual_km: int,
    lifetime_km: int,
    start: int,
    stop: int = END_YEAR,
    case: str = "baseline",
    first_year_km: float | None = None,
) -> dict:
    """Compose repeated whole-vehicle cohorts that provide continuous service."""
    annual: dict = {}
    cohorts = []
    cohort = first_cohort
    capacity = float(annual_km if first_year_km is None else first_year_km)
    service = {year: 0.0 for year in range(start, stop + 1)}
    while cohort <= stop:
        item = profile(
            cohort=cohort,
            powertrain=powertrain,
            size=size,
            annual_km=annual_km,
            lifetime_km=lifetime_km,
            case=case,
        )
        allocations, complete, final_use, leftover = _allocate_vehicle(
            cohort, capacity, annual_km, lifetime_km, stop
        )
        _add_scheduled_vehicle(
            annual, item, allocations,
            complete=complete, final_use_year=final_use, stop=stop,
        )
        for year, distance in allocations.items():
            service[year] = service.get(year, 0.0) + distance
        cohorts.append(
            {
                "cohort": cohort,
                "last_use": min(final_use, stop),
                "powertrain": powertrain,
                "size": size,
                "first_year_km": allocations.get(cohort, 0.0),
                "service_km": sum(allocations.values()),
            }
        )
        if not complete:
            break
        if leftover > 1e-9:
            cohort = final_use
            capacity = leftover
        else:
            cohort = final_use + 1
            capacity = float(annual_km)
    return {"annual": annual, "cohorts": cohorts, "service": service}


def ownership_case(
    *,
    decision_year: int = 2026,
    annual_km: int = 12_000,
    lifetime_km: int = 200_000,
    successor: str = "BEV",
    size: str = "Medium",
    case: str = "baseline",
    successor_case: str | None = None,
    end_year: int = END_YEAR,
) -> dict:
    """Return owner-level keep and replace timelines.

    Replacement happens after the selected calendar year.  The original car's
    later use and end-of-life are outside the owner's boundary.  Both paths
    include the same historical original-car impacts and provide continuous
    service through ``end_year``.
    """
    successor_case = successor_case or case
    original = profile(
        cohort=CURRENT_START,
        powertrain="ICEV-p",
        size="Medium",
        annual_km=annual_km,
        lifetime_km=lifetime_km,
        case=case,
    )
    natural_end = last_use_year(CURRENT_START, annual_km, lifetime_km)
    if decision_year > natural_end:
        return {"valid": False, "reason": "The current car has already reached its assumed lifetime."}

    keep = {"annual": {}, "cohorts": [], "service": {year: 0.0 for year in range(CURRENT_START, end_year + 1)}}
    replace = {"annual": {}, "cohorts": [], "service": {year: 0.0 for year in range(CURRENT_START, end_year + 1)}}
    keep_allocations, keep_complete, keep_final, keep_leftover = _allocate_vehicle(
        CURRENT_START, annual_km, annual_km, lifetime_km, end_year
    )
    _add_scheduled_vehicle(
        keep["annual"], original, keep_allocations,
        complete=keep_complete, final_use_year=keep_final, stop=end_year,
    )
    for year, distance in keep_allocations.items():
        keep["service"][year] += distance

    replace_allocations, replace_complete, replace_final, replace_leftover = _allocate_vehicle(
        CURRENT_START, annual_km, annual_km, lifetime_km, decision_year
    )
    _add_scheduled_vehicle(
        replace["annual"], original, replace_allocations,
        complete=False, final_use_year=replace_final, stop=end_year,
    )
    for year, distance in replace_allocations.items():
        replace["service"][year] += distance
    keep["cohorts"].append(
        {"cohort": CURRENT_START, "last_use": keep_final, "powertrain": "ICEV-p", "size": "Medium", "first_year_km": annual_km, "service_km": sum(keep_allocations.values())}
    )
    replace["cohorts"].append(
        {"cohort": CURRENT_START, "last_use": replace_final, "powertrain": "ICEV-p", "size": "Medium", "transferred": not replace_complete, "first_year_km": annual_km, "service_km": sum(replace_allocations.values())}
    )

    if keep_complete and keep_final < end_year:
        next_cohort = keep_final if keep_leftover > 1e-9 else keep_final + 1
        continuation = sequence(
            first_cohort=next_cohort,
            powertrain=successor,
            size=size,
            annual_km=annual_km,
            lifetime_km=lifetime_km,
            start=next_cohort,
            stop=end_year,
            case=successor_case,
            first_year_km=keep_leftover if keep_leftover > 1e-9 else annual_km,
        )
        keep["cohorts"].extend(continuation["cohorts"])
        _combine_annual(keep["annual"], continuation["annual"])
        for year, distance in continuation["service"].items():
            keep["service"][year] += distance

    if replace_complete and replace_leftover > 1e-9:
        replacement_start = replace_final
        replacement_first_year = replace_leftover
    else:
        replacement_start = replace_final + 1
        replacement_first_year = annual_km
    replacement = sequence(
        first_cohort=replacement_start,
        powertrain=successor,
        size=size,
        annual_km=annual_km,
        lifetime_km=lifetime_km,
        start=replacement_start,
        stop=end_year,
        case=successor_case,
        first_year_km=replacement_first_year,
    )
    replace["cohorts"].extend(replacement["cohorts"])
    _combine_annual(replace["annual"], replacement["annual"])
    for year, distance in replacement["service"].items():
        replace["service"][year] += distance
    return {"valid": True, "keep": keep, "replace": replace}


def annual_totals(path: dict, category: str) -> dict[int, float]:
    return {
        int(year): sum(stages.values())
        for year, stages in path["annual"].get(category, {}).items()
    }


def cumulative(path: dict, category: str, start: int = 2018, stop: int = END_YEAR) -> list[float]:
    totals = annual_totals(path, category)
    running = 0.0
    values = []
    for year in range(start, stop + 1):
        running += totals.get(year, 0.0)
        values.append(running)
    return values


def cumulative_summary(case_result: dict | None = None, category: str = "climate change") -> dict:
    """Return the baseline cumulative crossing and end-horizon difference."""
    case_result = case_result or ownership_case()
    years = list(range(2018, END_YEAR + 1))
    keep = cumulative(case_result["keep"], category, start=2018)
    replace = cumulative(case_result["replace"], category, start=2018)
    crossing = next(
        (year for year, keep_value, replace_value in zip(years, keep, replace)
         if year > 2026 and replace_value <= keep_value),
        None,
    )
    return {
        "break_even_year": crossing,
        "keep_2060": keep[-1],
        "replace_2060": replace[-1],
        "delta_2060": replace[-1] - keep[-1],
    }


def total(path: dict, category: str, stop: int = END_YEAR) -> float:
    return sum(value for year, value in annual_totals(path, category).items() if year <= stop)


def delta(case_result: dict, category: str) -> float:
    return total(case_result["replace"], category) - total(case_result["keep"], category)


